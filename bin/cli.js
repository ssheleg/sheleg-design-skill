function resolveTargetDir(opts, cwd) {
  if (opts.target) return path.resolve(cwd, opts.target);
  if (opts.flavor === "cursor")
    return path.join(cwd, ".cursor", "skills", SKILL_SLUG);
  if (opts.flavor === "claude")
    return path.join(cwd, ".claude", "skills", SKILL_SLUG);

  const hasCursor = fs.existsSync(path.join(cwd, ".cursor"));
  const hasClaude = fs.existsSync(path.join(cwd, ".claude"));
  if (hasCursor) return path.join(cwd, ".cursor", "skills", SKILL_SLUG);
  if (hasClaude) return path.join(cwd, ".claude", "skills", SKILL_SLUG);
  return path.join(cwd, ".cursor", "skills", SKILL_SLUG);
}

function main() {
  const opts = parseArgs(process.argv.slice(2));

  if (opts.error) {
    console.error(c("yellow", `sheleg-design-skill: ${opts.error}`));
    printHelp();
    process.exit(2);
  }
  if (opts.version) {
    console.log(pkg.version);
    return;
  }
  if (opts.help) {
    printHelp();
    return;
  }

  const cwd = process.cwd();

  if (opts.kit) {
    runKit(opts, cwd);
    return;
  }

  const targetDir = resolveTargetDir(opts, cwd);

  // Verify the bundle is intact before touching the filesystem.
  for (const f of CORE_FILES) {
    if (!fs.existsSync(path.join(SKILL_DIR, f))) {
      console.error(
        c("yellow", `Bundle is missing ${f}. This is a packaging bug.`),
      );
      process.exit(1);
    }
  }

  const files = listBundleFiles();
  const existing = files.filter((f) =>
    fs.existsSync(path.join(targetDir, f)),
  );
  if (existing.length && !opts.force) {
    console.error(
      `\n${c("yellow", "Refusing to overwrite existing files:")}\n` +
        existing.map((f) => "  " + path.join(targetDir, f)).join("\n") +
        `\n\nRe-run with ${c("bold", "--force")} to overwrite.\n`,
    );
    process.exit(1);
  }

  fs.mkdirSync(targetDir, { recursive: true });
  for (const f of files) {
    const dest = path.join(targetDir, f);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(SKILL_DIR, f), dest);
  }

  const rel = path.relative(cwd, targetDir) || ".";
  console.log(
    `\n${c("green", "✓")} ${c("bold", "SHELEG Design")} installed to ${c("blue", rel + "/")}\n` +
      `  ${c("dim", "SKILL.md")}            the agent skill\n` +
      `  ${c("dim", "SHELEG_DESIGN.md")}    the full reference\n` +
      `  ${c("dim", "MOTION_DOCTRINE.md")}  whether to animate at all — read before any animation\n` +
      `  ${c("dim", "styles/")}             style packs + token CSS (instrument-console / editorial-luxury / workbench / briefing-room / atrium / orchard / field-notes / cyclorama / showroom / blueprint / prism / maquette / scoreboard / datasheet / manpage / pigeonhole / roster)\n\n` +
      `Your Cursor / Claude agent can now discover the skill and build\n` +
      `cinematic, scroll-driven pages — or style product UI (dashboards, admin,\n` +
      `internal tools) from a standalone pack — on its principles.\n\n` +
      `${c("dim", "Docs: " + pkg.homepage)}\n`,
  );

  offerRouters();
}

/**
 * Ask the family launcher to write the routing block, for this member only.
 *
 * Delegated rather than reimplemented, for three reasons. The block describes
 * what the machine actually has, so a lone member rendering the whole thing
 * would produce a table for routers nobody installed. `--member` limits the
 * write to the `sheleg-design` section and leaves everyone else's alone, which
 * is what lets the bundle and a single installer both write. And the launcher is
 * the only writer that copies the operator's global instruction file before
 * touching it — that file has no version control behind it.
 *
 * The registry name is `sheleg-design`, not the package name
 * `sheleg-design-skill`. The skill installs into a PROJECT while the block lives
 * in the agent's GLOBAL instructions, and offering the second from the first is
 * deliberate: a skill discoverable in one repository and routed to in none is
 * how the family's composition order goes unread.
 *
 * `--no-install` keeps this from silently downloading a package nobody asked
 * for; when the launcher is absent the command is printed rather than failing,
 * because ending an install in an error over an OPTIONAL follow-up reads as a
 * failed install.
 */
function offerRouters() {
  const { spawnSync } = require("child_process");
  const r = spawnSync(
    "npx",
    ["--no-install", "sshlg-skills", "routers", "--member", "sheleg-design"],
    { stdio: "inherit", shell: process.platform === "win32" },
  );
  if (r.status !== 0) {
    console.log(
      `To have this skill apply by default in every project, add the family's\n` +
        `routing block to your agent's global instructions:\n\n` +
        `  ${c("bold", "npx --yes sshlg-skills routers --member sheleg-design")}\n`,
    );
  }
}

main();
